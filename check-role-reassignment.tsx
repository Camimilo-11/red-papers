import './check-role-assignment';
import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {roleService} from './src/services/roleService';
import {authService} from './src/services/authService';
import {DEMO_ACCOUNTS} from './src/constants/demoAccounts';
import {RoleManagementView} from './src/components/roles/RoleManagementView';
const [teacher,dev,committee]=DEMO_ACCOUNTS;
authService.login(dev.user.email,dev.password);
assert.ok(renderToStaticMarkup(<RoleManagementView currentUser={dev.user} onChanged={()=>{}}/>).includes(teacher.user.email));
assert.equal(roleService.assign(teacher.user.id,'teacher').success,true);
authService.login(teacher.user.email,teacher.password);
assert.equal(authService.getCurrentUser()?.role,'teacher');
authService.login(dev.user.email,dev.password);
assert.equal(roleService.assign(teacher.user.id,'reviewer_demo').success,true);
assert.equal(roleService.assign(teacher.user.id,'teacher').success,true);
authService.login(teacher.user.email,teacher.password);
assert.equal(authService.getCurrentUser()?.role,'teacher');
authService.login(committee.user.email,committee.password);
assert.equal(roleService.assign(committee.user.id,'teacher').success,false);
console.log('PASS: promoted member remains visible; developer can restore teacher; login persists restored role; committee restrictions retained.');
